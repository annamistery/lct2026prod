def check(text):
    """Возвращает код запрета/отказа или None."""
    t = norm(text)
    for code, rx in (("minor", MINOR), ("pregnant", PREGNANT), ("driving", DRIVING), ("intoxicate", INTOXICATE),
                     ("quantity", QUANTITY), ("health", HEALTH), ("decline", DECLINE)):
        if re.search(rx, t):
            return code
    return None


BANNED_TONE = [
    r"обязательно (попробуйте|выпейте|возьмите|закажите)", r"не пожалеете", r"порадуйте себя", r"пора (открыть|выпить)",
    r"как насчёт бокал", r"как насчет бокал", r"расслабьтесь с", r"вы заслуживаете", r"невероятн\w+ вино",
    r"лучше всего (выпить|пить)", r"нужно выпить", r"стоит (выпить|попробовать)", r"настоятельно",
    r"наливайте", r"ещё один бокал", r"ещё по бокал", r"за компанию выпейте", r"без вина (не )?обойтись",
]


def check_tone(text):
    """Список найденных побуждающих оборотов (должен быть пуст)."""
    t = norm(text)
    return [rx for rx in BANNED_TONE if re.search(norm(rx), t)]


