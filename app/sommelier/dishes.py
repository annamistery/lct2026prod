def _axes_default():
    return dict(intensity=None, fat=0.0, acid=0.0, sweet=0.0, salt=0.0, heat=0.0)


def parse_dish(text):
    """Разбор фразы про еду -> профиль. Возвращает dict или None, если блюдо не распознано."""
    t = norm(text)
    ax = _axes_default()
    mains, mods, tags = [], [], set()
    for name, rx, axes, tg in MAIN:
        m = re.search(rx, t)
        if m:
            mains.append((name, m.group(0), axes, tg))
    # более специфичные (с более высокой интенсивностью/ранние в списке) — оставляем все, но 'рыба'/'сыр' общие
    # убираем общее совпадение, если найдено специфичное того же семейства
    names = {n for n, *_ in mains}
    if names & {"белая рыба", "жирная рыба", "суши", "устрицы", "морепродукты"}:
        mains = [x for x in mains if x[0] != "рыба"]
    if names & {"сыр мягкий", "сыр с плесенью", "пицца", "паста"}:
        mains = [x for x in mains if x[0] != "сыр твёрдый" or re.search(r"пармезан|чеддер|гауда|твердый|твёрдый|грюйер|выдержанный", t)]
    for name, rx, axes, tg, dint in MODIFIERS:
        m = re.search(rx, t)
        if m:
            mods.append((name, m.group(0), axes, tg, dint))
    if not mains and not any(n in ("острый соус/перец",) for n, *_ in mods):
        return None
    ints = []
    for _name, _hit, axes, tg in mains:
        for k, v in axes.items():
            if k == "intensity":
                ints.append(v)
            else:
                ax[k] = max(ax[k], v)
        tags |= tg
    base_int = max(ints) if ints else 2.5
    d_int = 0.0
    for _name, _hit, axes, tg, dint in mods:
        for k, v in axes.items():
            ax[k] = max(ax[k], v)
        tags |= tg
        d_int += dint
    # десерт побеждает по сладости, остальные яркие оси «громкого» соуса лишь добавляют
    ax["intensity"] = max(0.5, min(4.0, base_int + max(-0.5, min(0.9, d_int))))
    if ax["heat"] >= 2.5 and "острое" not in tags:
        tags.add("острое")
    region = None
    for r, rx in CUISINES:
        if re.search(rx, t):
            region = r
            break
    style = [s for s, rx in CUISINE_STYLES if re.search(rx, t)]
    course = next((c for c, rx in COURSES.items() if re.search(rx, t)), None)
    if "десерт" in tags and course is None:
        course = "десерт"
    # человекочитаемое резюме распознанного
    parsed = dict(
        axes={k: round(v, 1) for k, v in ax.items()},
        tags=sorted(tags),
        matched_main=[f"{n} («{h}»)" for n, h, *_ in mains],
        matched_modifiers=[f"{n} («{h}»)" for n, h, *_ in mods],
        region=region, cuisine_style=style, course=course,
    )
    return parsed


LEVEL_WORDS = [(0.8, "очень лёгкое"), (1.7, "лёгкое"), (2.5, "среднее"), (3.3, "насыщенное"), (9, "очень насыщенное")]


def describe_axes(p):
    a = p["axes"]
    parts = [f"интенсивность {next(w for lim, w in LEVEL_WORDS if a['intensity'] <= lim)}"]
    if a["fat"] >= 2.5:
        parts.append("жирное")
    if a["acid"] >= 2:
        parts.append("кислинка")
    if a["sweet"] >= 1.5:
        parts.append("сладкое")
    if a["salt"] >= 3:
        parts.append("солёное")
    if a["heat"] >= 2.5:
        parts.append("острое")
    elif a["heat"] >= 1.2:
        parts.append("с перчинкой")
    return ", ".join(parts)
